UiStrId ui_setting_label(RandoSettingId id)
{
	assert((unsigned)id < RANDO_SETTING_COUNT);
	return labels[id];
}

UiStrId ui_setting_value(RandoSettingId id, int value)
{
	assert(value >= 0 && value < rando_setting_value_count(id) && value < UI_SETTING_VALUES_MAX);
	return values[id][value];
}
