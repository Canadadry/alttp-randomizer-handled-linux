const char *ladx_item_name(int item)
{
	if (item < 0 || item >= LADX_ITEM_COUNT)
		return NULL;
	return names[item];
}

int ladx_item_find(const char *name)
{
	int i;

	for (i = 0; i < LADX_ITEM_COUNT; i++)
		if (strcmp(names[i], name) == 0)
			return i;
	return LADX_ITEM_NONE;
}
