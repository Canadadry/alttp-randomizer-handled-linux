static LadxSpriteKind set(LadxSpriteData *o, int n, ...)
{
	va_list ap;
	int i;

	va_start(ap, n);
	o->count = n;
	for (i = 0; i < n; i++) {
		o->pair[i].slot = va_arg(ap, int);
		o->pair[i].count = 1;
		o->pair[i].values[0] = va_arg(ap, int);
		o->pair[i].values[1] = 0;
	}
	va_end(ap);
	return LADX_SPRITE_DATA;
}

static LadxSpriteKind either(LadxSpriteData *o, int slot, int a, int b)
{
	o->count = 1;
	o->pair[0].slot = slot;
	o->pair[0].count = 2;
	o->pair[0].values[0] = a;
	o->pair[0].values[1] = b;
	return LADX_SPRITE_DATA;
}

